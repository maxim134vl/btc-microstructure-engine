def preservation_snapshot(stamp: str | None = None, *, write: bool = True) -> dict[str, Any]:
    stamp = stamp or stamp_now()
    visual = {rel: sha256_of(ROOT / rel) for rel in VISUAL_INVARIANT_FILES}
    datasets: dict[str, Any] = {}
    for rel in SEMANTIC_INVARIANT_DATASETS:
        path = ROOT / rel
        entry: dict[str, Any] = {"exists": path.exists(), "sha256": sha256_of(path)}
        if path.exists() and path.suffix == ".parquet":
            try:
                entry["rows"] = int(len(pd.read_parquet(path, columns=None)))
            except Exception as exc:
                entry["rows_error"] = str(exc)
        datasets[rel] = entry
    payload = {
        "generated_at": utc_now(),
        "stage": "S4_1_PRESERVATION",
        "stamp": stamp,
        "visual_invariant_files": visual,
        "semantic_invariant_datasets": datasets,
        "environment": {
            "BTC_ML_CONTINUATION_PROGRESSION": os.environ.get("BTC_ML_CONTINUATION_PROGRESSION", "0"),
            "PRICE_GATE": os.environ.get("PRICE_GATE", "OFF"),
        },
        "dashboard_redesign": False,
        "css_theme_changed": False,
    }
    if write:
        atomic_write_json(RESEARCH / f"s4_1_preservation_{stamp}.json", payload)
    return payload
