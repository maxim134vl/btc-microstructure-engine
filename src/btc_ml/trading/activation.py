def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def stamp_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")


def sha256_of(path: Path) -> str | None:
    if not path.exists() or not path.is_file():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _jsonl_rows(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = []
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return []
    for line in text.splitlines():
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _rel_to_root(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def intrabar_legacy_epoch_preflight() -> dict[str, Any]:
    """Inventory active LIVE1B intrabar epoch for S4.1 activation blockers."""
    detail: dict[str, Any] = {
        "active_epoch_path": _rel_to_root(INTRABAR_EPOCHS_ROOT / "active.json"),
        "open_positions": 0,
        "unconsumed_context_events": 0,
        "mode": "EMPTY",
    }
    active_path = INTRABAR_EPOCHS_ROOT / "active.json"
    if not active_path.exists():
        return detail
    try:
        active = json.loads(active_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        detail["mode"] = MODE_AMBIGUOUS
        detail["read_error"] = str(exc)
        return detail
    epoch_id = str(active.get("paper_epoch_id") or "")
    if not epoch_id:
        return detail
    detail["paper_epoch_id"] = epoch_id
    detail["rule_contract_version"] = active.get("rule_contract_version")
    books = INTRABAR_PAPER_ROOT / epoch_id / "books"
    positions = _jsonl_rows(books / "positions.jsonl")
    latest_by_id: dict[str, dict[str, Any]] = {}
    for row in positions:
        pid = str(row.get("position_id") or "")
        if pid:
            latest_by_id[pid] = row
    detail["open_positions"] = int(
        sum(1 for row in latest_by_id.values() if str(row.get("status") or "").upper() == "OPEN")
    )
    checkpoint_path = INTRABAR_PAPER_ROOT / epoch_id / "context_consumer_checkpoint.json"
    last_mono = 0
    if checkpoint_path.exists():
        try:
            ck = json.loads(checkpoint_path.read_text(encoding="utf-8"))
            last_mono = int(ck.get("last_event_monotonic_ns") or 0)
        except (OSError, json.JSONDecodeError):
            pass
    unconsumed = 0
    for path in sorted(INTRABAR_JOURNAL_ROOT.rglob("*.jsonl")) if INTRABAR_JOURNAL_ROOT.exists() else []:
        for row in _jsonl_rows(path):
            if str(row.get("epoch_id") or "") not in {"", epoch_id}:
                continue
            mono = int(row.get("event_monotonic_ns") or 0)
            if mono > last_mono:
                unconsumed += 1
    detail["unconsumed_context_events"] = unconsumed
    if detail["open_positions"] > 0 or detail["unconsumed_context_events"] > 0:
        detail["mode"] = MODE_OPEN_POSITION_PRESENT
        detail["blocking_status"] = BLOCKED_BY_LEGACY_INTRABAR_EPOCH
    else:
        detail["mode"] = MODE_EMPTY
    return detail


def legacy_ledger_mode() -> dict[str, Any]:
    positions_path = LEGACY_PAPER_DIR / "paper_positions.parquet"
    detail: dict[str, Any] = {
        "positions_path": str(positions_path.relative_to(ROOT)),
        "exists": positions_path.exists(),
        "rows": 0,
        "open_rows": 0,
        "closed_rows": 0,
        "unknown_status_rows": 0,
    }
    if not positions_path.exists():
        detail["mode"] = MODE_EMPTY
        return detail
    try:
        frame = pd.read_parquet(positions_path)
    except Exception as exc:
        detail["mode"] = MODE_AMBIGUOUS
        detail["read_error"] = str(exc)
        return detail
    detail["rows"] = int(len(frame))
    if not len(frame):
        detail["mode"] = MODE_EMPTY
        return detail
    status = frame["status"].astype(str).str.upper() if "status" in frame.columns else pd.Series(dtype=str)
    detail["open_rows"] = int((status == "OPEN").sum())
    detail["closed_rows"] = int((status == "CLOSED").sum())
    detail["unknown_status_rows"] = int(len(status) - detail["open_rows"] - detail["closed_rows"])
    if detail["open_rows"]:
        detail["mode"] = MODE_OPEN_POSITION_PRESENT
        detail["blocking_status"] = BLOCKED_BY_LEGACY_OPEN
    elif detail["unknown_status_rows"]:
        detail["mode"] = MODE_AMBIGUOUS
    else:
        detail["mode"] = MODE_CLOSED_HISTORY_ONLY
    return detail


def process_pids(needle: str) -> list[int]:
    try:
        out = subprocess.run(["ps", "-ax", "-o", "pid=,command="], capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return []
    pids: list[int] = []
    for line in out.splitlines():
        line = line.strip()
        if not line or needle not in line:
            continue
        if "ps -ax" in line or "timeframe_trading_ctl" in line:
            continue
        head = line.split(" ", 1)[0]
        try:
            pids.append(int(head))
        except ValueError:
            continue
    return pids


