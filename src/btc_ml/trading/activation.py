def evaluate_gates() -> dict[str, Any]:
    summary = candidate_summary() or {}
    gates = dict(summary.get("gates") or {})
    legacy = legacy_ledger_mode()
    intrabar = intrabar_legacy_epoch_preflight()
    checks = {
        "candidate_replay_passed": bool(gates.get("candidate_replay_passed")),
        "opposite_positions_test_passed": bool(gates.get("opposite_positions_test_passed")),
        "restart_isolation_passed": bool(gates.get("restart_isolation_passed")),
        "portfolio_risk_passed": bool(gates.get("portfolio_risk_passed")),
        "point_in_time_fill_passed": bool(gates.get("point_in_time_fill_passed")),
        "pnl_reconciliation_passed": bool(gates.get("pnl_reconciliation_passed")),
        "legacy_open_position": legacy.get("mode") == MODE_OPEN_POSITION_PRESENT,
        "legacy_mode_unambiguous": legacy.get("mode") in {MODE_EMPTY, MODE_CLOSED_HISTORY_ONLY},
        "intrabar_legacy_epoch_clean": intrabar.get("mode") == MODE_EMPTY,
        "unexplained_divergences": 0,
        "exchange_calls": 0,
    }
    blocked_reasons = [
        name
        for name in (
            "candidate_replay_passed",
            "opposite_positions_test_passed",
            "restart_isolation_passed",
            "portfolio_risk_passed",
            "point_in_time_fill_passed",
            "pnl_reconciliation_passed",
            "legacy_mode_unambiguous",
            "intrabar_legacy_epoch_clean",
        )
        if not checks[name]
    ]
    if checks["legacy_open_position"]:
        blocked_reasons.append(BLOCKED_BY_LEGACY_OPEN)
    if not checks["intrabar_legacy_epoch_clean"]:
        blocked_reasons.append(BLOCKED_BY_LEGACY_INTRABAR_EPOCH)
    return {
        "generated_at": utc_now(),
        "checks": checks,
        "legacy_ledger": legacy,
        "intrabar_legacy_epoch": intrabar,
        "candidate_status": summary.get("candidate_status"),
        "allowed": not blocked_reasons,
        "blocked_reasons": blocked_reasons,
    }


def create_backups(stamp: str | None = None) -> dict[str, Any]:
    stamp = stamp or stamp_now()
    backup_dir = RESEARCH / f"s4_1_production_backups_{stamp}"
    backup_dir.mkdir(parents=True, exist_ok=True)
    entries: list[dict[str, Any]] = []

    def copy_tree(source: Path, label: str) -> None:
        if not source.exists():
            return
        target = backup_dir / label
        if source.is_dir():
            shutil.copytree(source, target, dirs_exist_ok=True)
            for path in sorted(target.rglob("*")):
                if path.is_file():
                    entries.append(
                        {
                            "label": label,
                            "backup_path": str(path.relative_to(ROOT)),
                            "sha256": sha256_of(path),
                            "bytes": path.stat().st_size,
                        }
                    )
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            entries.append(
                {
                    "label": label,
                    "source_path": str(source.relative_to(ROOT)),
                    "backup_path": str(target.relative_to(ROOT)),
                    "sha256": sha256_of(target),
                    "bytes": target.stat().st_size,
                }
            )

    copy_tree(LEGACY_PAPER_DIR, "legacy_paper_simulator")
    copy_tree(ROOT / "data" / "trading", "timeframe_trading")
    copy_tree(ROOT / "config" / "timeframe_trader_risk.json", "config_timeframe_trader_risk.json")
    copy_tree(ROOT / "config" / "runtime_dataset_ownership.json", "config_runtime_dataset_ownership.json")

    manifest = {
        "generated_at": utc_now(),
        "stage": "S4_1_PRODUCTION_BACKUP",
        "stamp": stamp,
        "backup_dir": str(backup_dir.relative_to(ROOT)),
        "files": entries,
        "file_count": len(entries),
    }
    manifest_path = RESEARCH / f"s4_1_backup_manifest_{stamp}.json"
    atomic_write_json(manifest_path, manifest)
    manifest["manifest_path"] = str(manifest_path.relative_to(ROOT))
    return manifest


def archive_legacy_ledger(stamp: str | None = None, *, mode: str | None = None) -> dict[str, Any]:
    """Copy the legacy paper ledger into an immutable historical book.

    The archived copy is chmod 444. The originals stay in place and writable:
    dashboards, history readers and audit tests copy them into throwaway roots,
    and a read-only source mode would propagate into those copies. The freeze is
    enforced instead by stopping the legacy controller, by the ctl start guard
    and by the OPS alert that fires if it ever runs after the cutover.

    Legacy trades are never reassigned to timeframes.
    """
    stamp = stamp or stamp_now()
    archive_dir = ROOT / "data" / "archive" / f"legacy_global_paper_ledger_{stamp}"
    archive_dir.mkdir(parents=True, exist_ok=True)
    archived: list[str] = []
    immutable: list[str] = []
    for name in LEGACY_LEDGER_FILES:
        source = LEGACY_PAPER_DIR / name
        for path in (source, source.with_suffix(source.suffix + ".meta.json")):
            if not path.is_file():
                continue
            target = archive_dir / path.name
            shutil.copy2(path, target)
            os.chmod(target, 0o444)
            archived.append(path.name)
            immutable.append(str(target.relative_to(ROOT)))
    payload = {
        "generated_at": utc_now(),
        "legacy_ledger_state": "ARCHIVED_READ_ONLY",
        "legacy_mode_at_cutover": mode or legacy_ledger_mode().get("mode"),
        "archive_dir": str(archive_dir.relative_to(ROOT)),
        "archived_files": archived,
        "immutable_archive_paths": immutable,
        "source_paths": [
            str((LEGACY_PAPER_DIR / name).relative_to(ROOT))
            for name in LEGACY_LEDGER_FILES
            if (LEGACY_PAPER_DIR / name).is_file()
        ],
        "source_write_freeze_enforced_by": [
            "legacy_controller_stopped_at_cutover",
            "ctl_start_guard_after_activation",
            "ops_alert_LEGACY_PAPER_CONTROLLER_RUNNING_AFTER_CUTOVER",
        ],
        "history_reassigned_to_timeframes": False,
        "legacy_book_role": "READ_ONLY_HISTORICAL_BOOK",
    }
    atomic_write_json(LEGACY_MIGRATION_PATH, payload)
    return payload


def restore_legacy_writable(*, names: tuple[str, ...] = LEGACY_LEDGER_FILES) -> list[str]:
    restored: list[str] = []
    for name in names:
        source = LEGACY_PAPER_DIR / name
        if not source.is_file():
            continue
        os.chmod(source, 0o644)
        restored.append(str(source.relative_to(ROOT)))
    return restored


