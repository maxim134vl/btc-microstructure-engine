def paper_permission(config, cutoff):
    """Read an explicit independently pinned config, never an incoming grant."""
    pin = config.get('paper_permission')
    if not isinstance(pin, dict) or set(pin) != {'path', 'sha256'}:
        raise Blocked('PAPER_PERMISSION_REQUIRED')
    path = Path(pin['path'])
    if not path.is_absolute():
        raise Blocked('PAPER_PERMISSION_PATH')
    value = _json(_read(path, pin['sha256']))
    if (value.get('contract') != PAPER_CONTRACT or value.get('mode') != 'PAPER'
            or value.get('real_execution_enabled') is not False
            or value.get('complete_venue_coverage') is not False
            or value.get('capture_family') != config.get('capture_family')
            or value.get('market') != config.get('market')
            or set(value.get('timeframes', [])) != set(config.get('timeframes', []))):
        raise Blocked('PAPER_PERMISSION_SCOPE')
    if utc(value['effective_at']) > utc(cutoff):
        raise Blocked('PAPER_PERMISSION_NOT_YET_AVAILABLE')
    level = value.get('evidence_level')
    if ((level == 'TEST_ONLY' and config.get('mode') != 'FIXTURE_ONLY')
            or (level == 'OBSERVED' and config.get('mode') != 'REAL_CANDIDATE')
            or level not in ('TEST_ONLY', 'OBSERVED')):
        raise Blocked('PAPER_EVIDENCE_LEVEL')
    if level == 'TEST_ONLY':
        for key in ('context_root', 'financial_root'):
            if key not in value: continue  # Classification tests need no executor.
            root = Path(value[key]).resolve()
            if ('TEST_ONLY' not in str(root) or not any(root.is_relative_to(base)
                    for base in (Path('/private/tmp'), Path('/Volumes/MaksTiger')))):
                raise Blocked('PAPER_TEST_PERMISSION_ON_WORKING_ROOT')
    return value


def verify_paper_source(config, raw, cutoff, *, records=(), fixture_authorized=False):
    """Check original source membership, not absolute exchange completeness.

    TEST_ONLY uses the existing finite FixtureAuthority. OBSERVED uses the
    original canary reader and its retained post-commit receipts. No historical
    grant is written into either capture or receipt.
    """
    permission = paper_permission(config, cutoff)
    if utc(permission['effective_at']) > utc(raw.trade.trade_time):
        raise Blocked('PAPER_RETROACTIVE_SOURCE_ADMISSION')
    if permission['evidence_level'] == 'TEST_ONLY':
        if not fixture_authorized:
            raise Blocked('PAPER_TEST_SOURCE_UNAUTHORIZED')
        return {'level': 'TEST_ONLY', 'venue_completeness': 'UNKNOWN_NOT_ASSERTED'}
    candidates = []
    for record in records:
        a = record['action']
        if a.get('kind') == 'RETAINED_CANARY_SOURCE':
            for d in a['evidence']['deliveries']:
                if (d['source_key'] == raw.trade.source_key
                        and d['core_sha256'] == raw.trade.payload_sha
                        and d['coverage_ref'] == raw.coverage_ref
                        and d['available_by'] == raw.available_at):
                    candidates.append(a['evidence'])
    if not candidates:
        raise Blocked('PAPER_ORIGINAL_DELIVERY_RECEIPT_REQUIRED')
    # Re-open native evidence instead of trusting caller flags / a transport ACK.
    capture = read_retained_canary(trust_from_config(config), capture_id=candidates[-1]['capture_id'], cutoff=cutoff)
    if capture['manifest_tip_sha256'] != candidates[-1]['manifest_tip_sha256']:
        raise Blocked('PAPER_CAPTURE_VERSION_CONFLICT')
    deliveries = [d for d in capture['deliveries'] if d['packet'] == raw.packet()]
    if len(deliveries) != 1:
        raise Blocked('PAPER_RAW_RECEIPT_IDENTITY')
    # A known discontinuity cannot be relabelled unknown/full coverage.
    if capture['observed_discontinuities'] or capture['pending_queue'] or len(capture['sessions']) != 1:
        raise Blocked('PAPER_SOURCE_DISCONTINUITY_OR_PENDING_LOSS')
    sequences = [int(d['delivery_id'].rsplit(':', 1)[1]) for d in capture['deliveries']]
    if sequences != list(range(1, len(sequences) + 1)):
        raise Blocked('PAPER_LOCAL_DELIVERY_SEQUENCE_GAP')
    known = {'CAPTURE_SCOPE', 'SESSION_STARTED', 'TRANSPORT_SESSION_OBSERVATION', 'DELIVERY', 'QUEUE_DEQUEUED'}
    if any(record['type'] not in known for record in capture['records']):
        raise Blocked('PAPER_UNASSESSED_SOURCE_EVENT')
    return {'level': 'OBSERVED', 'receipt_sha256': deliveries[0]['ack_sha256'],
            'venue_completeness': 'UNKNOWN_NOT_ASSERTED',
            'aggressor_semantics': deliveries[0]['aggression']}


def verify_paper_context_baseline(config, tf, cutoff):
    permission = paper_permission(config, cutoff)
    own = config.get('contexts', {}).get(tf)
    if not own or not config.get('baseline') or not config.get('baseline_available_at'):
        raise Blocked('PAPER_CONTEXT_OR_BASELINE_UNAVAILABLE')
    if tf not in permission['timeframes']:
        raise Blocked('PAPER_OWN_TF_REQUIRED')
    if permission['evidence_level'] == 'TEST_ONLY':
        # Native authored fixtures retain their explicit namespace/proof checks.
        if config.get('mode') != 'FIXTURE_ONLY':
            raise Blocked('PAPER_TEST_CONTEXT_NAMESPACE')
        return
    if not config.get('paper_context_root') or not config.get('paper_capture_id'):
        raise Blocked('PAPER_CONTEXT_OR_CAPTURE_BINDING_REQUIRED')
    root = Path(config['paper_context_root'])
    from btc_ml.runtime.financial_trend_environment import load_own_inputs
    from btc_ml.trading.timeframe_state_adapter import resolve_timeframe_state
    from btc_ml.external_traders.context_phase_publication import verify_live_context_phase
    sources, _ = load_own_inputs(root)
    state = resolve_timeframe_state(timeframe=tf, evaluation_timestamp=cutoff, sources=sources, now=cutoff, prefer_forming=False)
    verified = verify_live_context_phase(root, tf, state, cutoff)
    if (verified.get('qualification') != 'LIVE_QUALIFIED'
            or state.get('lifecycle_episode_id') != own['id']
            or state.get('timeframe_direction') != own['direction']):
        raise Blocked('PAPER_GENUINE_CONTEXT_BINDING')
    from btc_ml.external_traders.context_phase_publication import _verified_generation
    generation = _verified_generation(root, tf, verified['source_publication_ref'])
    actual_context_publication = generation['manifest']['native_publication_witness']['source_publication_completed_at']
    if utc(own['available_at']) < utc(actual_context_publication):
        raise Blocked('PAPER_CONTEXT_PUBLICATION_CLOCK_NOT_PROVEN')
    # Baseline trades need the same original raw/receipt proof as the initiative.
    capture = read_retained_canary(trust_from_config(config), capture_id=config['paper_capture_id'], cutoff=cutoff)
    allowed = {d['packet']['trade']['native_id']: d for d in capture['deliveries']}
    for trade in config['baseline']:
        d = allowed.get(trade['native_id'])
        if not d or d['packet']['trade'] != trade or utc(d['available_by']) > utc(config['baseline_available_at']):
            raise Blocked('PAPER_BASELINE_SOURCE_NOT_PROVEN')
    predecessor = allowed.get(config['predecessor'])
    if not predecessor or utc(predecessor['available_by']) > utc(config['policy_available_at']):
        raise Blocked('PAPER_PREDECESSOR_NOT_PROVEN')


def paper_segment(state, segment):
    """Revalidate qualified ancestry/membership at bridge and consumption."""
    if not segment or segment.get('authority_class') != PAPER_CLASS:
        raise Blocked('PAPER_QUALIFIED_SEGMENT_REQUIRED')
    c = state['config']; paper_permission(c, segment['cutoff'])
    parent = state['economic'].get(segment['parent_id'])
    if not parent or parent['authority_class'] not in (PAPER_SEED, PAPER_CLASS):
        raise Blocked('PAPER_SEED_ANCESTOR_REQUIRED')
    if (parent['tf'], parent['context'], parent['direction']) != (segment['tf'], segment['context'], segment['direction']):
        raise Blocked('PAPER_PARENT_SCOPE_MISMATCH')
    if set(parent['source_ids']) & set(segment['source_ids']):
        raise Blocked('PAPER_SOURCE_REUSE')
    if state['tf'][segment['tf']]['blocked']:
        raise Blocked('PAPER_DEPENDENT_SOURCE_BLOCKED')
    for value in segment['windows']:
        observation = obs_restore(value)
        error = observation.validate(segment['cutoff'])
        if error:
            raise Blocked('PAPER_' + error)
        if (observation.tf, observation.context_id, observation.context_direction) != (segment['tf'], segment['context'], segment['direction']):
            raise Blocked('PAPER_WINDOW_SCOPE_MISMATCH')
    if any(not state['raw'][k].get('paper_authorized') for k in segment['source_ids']):
        raise Blocked('PAPER_SOURCE_AUTHORITY_MISSING')
    return segment
