"""Read-only REAL_SCOPE_PROOF_V1 verification; never an OPEN/economic grant.

Trust is an independently pinned inventory supplied outside the incoming proof.
This module never writes a receipt, reconstructs receive clocks, or translates
normalized archive rows/Stage2 aggregates into RawOccurrence. Unavailable native
capture evidence remains a rejection. Existing fixture admission is separate.
"""
from __future__ import annotations
from dataclasses import dataclass
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from typing import Any, Mapping
import json

from .trend_journal import Blocked
from .trend_event import DUR, Observation, utc
from .trend_evidence import RawOccurrence, obs_restore

VERSION = 'REAL_SCOPE_PROOF_V1'
MAX_EVIDENCE_BYTES = 8 * 1024 * 1024  # Same bounded native journal record budget.


def _json(raw: bytes):
    def unique(pairs):
        out = {}
        for key, value in pairs:
            if key in out:
                raise Blocked('REAL_DUPLICATE_JSON_KEY')
            out[key] = value
        return out
    try:
        return json.loads(raw, object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(ValueError()))
    except (ValueError, TypeError, UnicodeError) as exc:
        raise Blocked('REAL_INVALID_JSON') from exc


def _read(path: Path, expected_sha: str) -> bytes:
    if not isinstance(expected_sha, str) or len(expected_sha) != 64:
        raise Blocked('REAL_SHA_PIN_REQUIRED')
    try:
        # Read the actual bytes, never trust mtime or an input verified flag.
        with path.open('rb') as stream:
            raw = stream.read(MAX_EVIDENCE_BYTES + 1)
    except OSError as exc:
        raise Blocked('REAL_EVIDENCE_UNAVAILABLE:' + str(path)) from exc
    if len(raw) > MAX_EVIDENCE_BYTES:
        raise Blocked('REAL_EVIDENCE_RESOURCE_CAP')
    if sha256(raw).hexdigest() != expected_sha:
        raise Blocked('REAL_EVIDENCE_SHA_MISMATCH:' + str(path))
    return raw


@dataclass(frozen=True)
class RealScopeTrust:
    """Out-of-band journal-config pin, NOT a field accepted from a proof dict.

    The inventory must refer to retained original receipts and native capture;
    constructing an inventory today does not confer historical availability.
    No inventory or producer approval is generated by this implementation.
    """
    path: Path
    sha256: str

    def inventory(self) -> dict:
        value = _json(_read(Path(self.path), self.sha256))
        if not isinstance(value, dict) or value.get('version') != VERSION:
            raise Blocked('REAL_TRUST_SCHEMA')
        for field in ('files', 'receipts', 'producers'):
            if not isinstance(value.get(field), dict):
                raise Blocked('REAL_TRUST_SCHEMA')
        return value


def trust_from_config(config: Mapping[str, Any]) -> RealScopeTrust:
    pin = config.get('real_scope_trust')
    if not isinstance(pin, dict) or set(pin) != {'path', 'sha256'}:
        raise Blocked('REAL_SCOPE_TRUST_NOT_CONFIGURED')
    path = Path(pin['path'])
    if not path.is_absolute():
        raise Blocked('REAL_TRUST_ABSOLUTE_PATH_REQUIRED')
    return RealScopeTrust(path, pin['sha256'])


def verify_real_scope_proof(proof: Mapping[str, Any], *, trust: RealScopeTrust,
                            timeframe: str, cutoff: str) -> None:
    """Verify bytes, independent pins, own scope and native causal constituents.

    PARTIAL IMPLEMENTATION: source-authority receipt semantics are unavailable
    in the retained capture. Full REAL admission is therefore fail-closed; this
    function currently returns NO positive capability. Do not remove that limit
    until the genuine upstream contract can be checked.

    A V1 envelope is only a set of refs to retained ORIGINAL evidence. It cannot
    authorize its own files/producers, supply a historical publication clock, or
    stand in for missing original raw/capture/publication records. No economics
    or R2 event is inferred from a verified source scope.
    """
    if type(trust) is not RealScopeTrust:
        raise Blocked('REAL_TRUST_OBJECT_REQUIRED')
    if not isinstance(proof, Mapping) or proof.get('version') != VERSION:
        raise Blocked('REAL_SCOPE_PROOF_REQUIRED')
    if proof.get('origin') != 'REAL_CANDIDATE' or timeframe not in DUR:
        raise Blocked('REAL_SCOPE_OR_ORIGIN')
    if proof.get('timeframe', timeframe) != timeframe:
        raise Blocked('REAL_SCOPE_IDENTITY_MISMATCH')
    try:
        utc(cutoff)
        inv = trust.inventory()
        receipt_id = proof.get('receipt_id')
        ref = inv['receipts'].get(receipt_id)
        if not isinstance(ref, dict):
            raise Blocked('REAL_ORIGINAL_RECEIPT_MISSING')
        receipt_bytes = _read(Path(ref['path']), ref['sha256'])
        receipt = _json(receipt_bytes)
        # Consume the existing post-write envelope, not a newly fabricated
        # receipt with today's REAL_SCOPE_PROOF_V1 version stamped on history.
        native = receipt.get('publication_evidence')
        if (receipt.get('publication_evidence_version')!='stage2_post_write_publication_v1'
            or not isinstance(native,dict) or native.get('receipt_id')!=receipt_id
            or (native.get('source_contract') or {}).get('filename') not in
               ('final_market_context_memory.parquet','market_context_lifecycle_memory.parquet')):
            raise Blocked('REAL_NATIVE_SCOPE_RECEIPT_UNAVAILABLE')
        scope = native.get('scope')
        if not isinstance(scope,dict):
            raise Blocked('REAL_CONTEXT_GENERATION_ROW_WITNESS_MISSING')
        required_scope = ('market', 'symbol', 'stream', 'native_scope', 'timeframe',
                          'session_id', 'event_id', 'generation', 'canonical_episode_id',
                          'direction', 'source_bar_open', 'source_bar_close')
        if any(not isinstance(scope.get(k), str) or not scope[k] for k in required_scope):
            raise Blocked('REAL_SCOPE_IDENTITY_INCOMPLETE')
        if proof.get('scope') != scope or scope['timeframe'] != timeframe:
            raise Blocked('REAL_SCOPE_IDENTITY_MISMATCH')
        if (scope['market'], scope['symbol'], scope['stream']) != ('BINANCE_SPOT', 'BTCUSDT', 'AGG_TRADE'):
            raise Blocked('REAL_NATIVE_SOURCE_DOMAIN')
        verify_pinned_producer(inv, native.get('producer'), native.get('producer_source_sha256'))
        completed = utc(native['publication_completed_at'])
        # available_by must be pinned separately from the incoming receipt. It
        # is a retained witness bound, never filesystem mtime or today's read.
        verify_publication_window(native['publication_completed_at'],ref['available_by'],cutoff)

        def file_bytes(key):
            pin = inv['files'].get(key)
            if not isinstance(pin, dict):
                raise Blocked('REAL_SOURCE_PIN_MISSING')
            return _read(Path(pin['path']), pin['sha256'])

        context_ref = native['context']
        raw_context = file_bytes(context_ref['artifact_ref'])
        if sha256(raw_context).hexdigest() != context_ref['artifact_sha256']:
            raise Blocked('REAL_CONTEXT_ARTIFACT_MISMATCH')
        import pandas as pd
        frame = pd.read_parquet(BytesIO(raw_context))
        if 'timeframe' not in frame or 'timestamp' not in frame:
            raise Blocked('REAL_OWN_CONTEXT_SCHEMA')
        own = frame.loc[frame.timeframe.eq(timeframe) &
                        pd.to_datetime(frame.timestamp, utc=True).eq(pd.Timestamp(scope['source_bar_open']))]
        if len(own) != 1:
            raise Blocked('REAL_EXACT_CONTEXT_ROW_REQUIRED')
        # Row bytes are canonical JSON produced by the original publication,
        # retained and pinned independently, not reconstructed from a snapshot.
        row_bytes = file_bytes(context_ref['row_ref'])
        row = _json(row_bytes)
        if sha256(row_bytes).hexdigest() != context_ref['row_sha256']:
            raise Blocked('REAL_CONTEXT_ROW_SHA_MISMATCH')
        native_row = json.loads(own.to_json(orient='records', date_format='iso', date_unit='ns'))[0]
        if row != native_row:
            raise Blocked('REAL_CONTEXT_ROW_BINDING_MISMATCH')
        from btc_ml.trading.timeframe_state_adapter import _episode_id_for_timeframe
        episode=_episode_id_for_timeframe(timeframe,row.get('context_episode_id',row.get('episode_id')))
        if (row.get('timeframe'),episode) != (timeframe, scope['canonical_episode_id']):
            raise Blocked('REAL_EPISODE_BINDING_MISMATCH')
        opened, closed = utc(scope['source_bar_open']), utc(scope['source_bar_close'])
        if (closed-opened).total_seconds() != DUR[timeframe] or opened.timestamp() % DUR[timeframe]:
            raise Blocked('REAL_OWN_BAR_ALIGNMENT')
        if not closed <= completed:
            raise Blocked('REAL_CONTEXT_BEFORE_CLOSE')

        # The original context receipt and the later recorder snapshot have
        # independent refs. The publisher is not required to predict future raw.
        capture_id = proof.get('retained_capture_id')
        if capture_id is not None:
            capture = _read_retained_canary_inventory(inv, capture_id=capture_id, cutoff=cutoff)
            deliveries = capture['deliveries']
            if not deliveries or any(d['packet']['capture_family'] != scope['session_id'] for d in deliveries):
                raise Blocked('REAL_RAW_SESSION_OR_COVERAGE')
            for delivery in deliveries:
                verify_capture_window(context_completed_at=receipt['publication_evidence']['publication_completed_at'],
                    context_available_by=ref['available_by'],raw_available_at=delivery['packet']['available_at'],
                    raw_available_by=delivery['available_by'],cutoff=cutoff,
                    raw_event_time=delivery['packet']['trade']['trade_time'])
            observations = _json(file_bytes(proof['observations_ref']))
            from .trend_event import Trade
            validate_native_observations(observations, cutoff=cutoff, timeframe=timeframe,
                context_id=scope['canonical_episode_id'],
                trades=[Trade(**d['packet']['trade']) for d in deliveries],
                context_available_at=receipt['publication_evidence']['publication_completed_at'])
            # The actual V2 coverage/aggression contracts say UNQUALIFIED.
            # Parsing their bytes is not approval of an alternative meaning.
            raise Blocked('REAL_SOURCE_COVERAGE_UNQUALIFIED')
        capture = native['raw_capture']
        # Full native packets and literal WS bytes are independent mandatory
        # artifacts. A normalized archive's raw_payload_hash cannot replace them.
        packets = _json(file_bytes(capture['raw_occurrences_ref']))
        wire = _json(file_bytes(capture['native_messages_ref']))
        if not isinstance(packets, list) or not packets or not isinstance(wire, list) or len(wire) != len(packets):
            raise Blocked('REAL_NATIVE_COVERAGE_MISSING')
        observations = _json(file_bytes(native['observations_ref']))
        if not isinstance(observations, list) or not observations:
            raise Blocked('REAL_NATIVE_OBSERVATIONS_MISSING')
        native = []
        predecessor = capture['predecessor']
        for packet, message in zip(packets, wire):
            p = RawOccurrence.from_dict(packet); p.validate(cutoff)
            if (p.trade.market,p.trade.symbol,p.trade.stream)!=(scope['market'],scope['symbol'],scope['stream']):
                raise Blocked('REAL_NATIVE_SOURCE_DOMAIN')
            if p.capture_origin != 'REAL_CANDIDATE' or (p.capture_family, p.coverage_ref) != (scope['session_id'], capture['coverage_ref']):
                raise Blocked('REAL_RAW_SESSION_OR_COVERAGE')
            if p.predecessor != predecessor or p.trade.native_id != predecessor + 1:
                raise Blocked('REAL_NATIVE_COVERAGE_GAP')
            predecessor = p.trade.native_id
            if not isinstance(message, str):
                raise Blocked('REAL_LITERAL_NATIVE_MESSAGE_REQUIRED')
            data = _json(message.encode())
            # Check the original lexical measurements; do not manufacture Trade.
            if (data['a'], data['s'], data['p'], data['q'], data['m']) != (p.trade.native_id, p.trade.symbol, p.trade.price, p.trade.quantity, p.trade.buyer_is_maker):
                raise Blocked('REAL_NATIVE_MESSAGE_MISMATCH')
            if pd.Timestamp(data['T'], unit='ms', tz='UTC') != pd.Timestamp(p.trade.trade_time) or pd.Timestamp(data['E'], unit='ms', tz='UTC') != pd.Timestamp(p.trade.exchange_event_time):
                raise Blocked('REAL_NATIVE_MESSAGE_CLOCK_MISMATCH')
            if not utc(p.available_at) <= completed:
                raise Blocked('REAL_RAW_AFTER_PUBLICATION')
            native.append(p.trade)
        validate_native_observations(observations, cutoff=cutoff, timeframe=timeframe,
                                     context_id=scope['canonical_episode_id'], trades=native)
        # Independently pinned parent bytes are necessary but are not a parser
        # or proof of source authority. Do not infer semantics from booleans.
        for key in ('transport_receipt_id', 'coverage_receipt_id', 'ownership_receipt_id'):
            parent_id = capture.get(key); parent_ref = inv['receipts'].get(parent_id)
            if not isinstance(parent_ref, dict):
                raise Blocked('REAL_' + key.upper() + '_MISSING')
            _read(Path(parent_ref['path']), parent_ref['sha256'])
        raise Blocked('REAL_NATIVE_SOURCE_AUTHORITY_CONTRACT_UNAVAILABLE')
    except Blocked:
        raise
    except (KeyError, TypeError, ValueError, AttributeError, OverflowError, OSError) as exc:
        raise Blocked('REAL_INCOMPLETE_NATIVE_PROOF') from exc


def verify_pinned_producer(inventory, producer_name, source_sha):
    producer=inventory['producers'].get(producer_name)
    if not isinstance(producer,dict) or source_sha!=producer.get('sha256'):
        raise Blocked('REAL_PRODUCER_NOT_AUTHORIZED')
    _read(Path(producer['path']),producer['sha256'])


def verify_publication_window(completed_at, retained_available_by, cutoff):
    if not utc(completed_at)<=utc(retained_available_by)<=utc(cutoff):
        raise Blocked('REAL_PUBLICATION_AFTER_ADMISSION')


def validate_native_observations(observations, *, cutoff, timeframe, context_id, trades, context_available_at=None):
    """Original D1–D7 prerequisites, not a classifier or ownership assertion."""
    covered = set()
    allowed = {t.source_key: t for t in trades}
    for value in observations:
        try:
            o: Observation = obs_restore(value)
        except (KeyError,TypeError,ValueError) as exc:
            raise Blocked('REAL_NATIVE_OBSERVATION_SCHEMA') from exc
        if (o.origin, o.tf, o.context_id) != ('REAL_CANDIDATE', timeframe, context_id):
            raise Blocked('REAL_OBSERVATION_SCOPE')
        if context_available_at is not None and utc(o.context_available_at) != utc(context_available_at):
            raise Blocked('REAL_CONTEXT_AVAILABILITY_BINDING')
        if error := o.validate(cutoff):
            raise Blocked('REAL_NATIVE_' + error)
        for trade in o.trades:
            if allowed.get(trade.source_key) != trade or trade.source_key in covered:
                raise Blocked('REAL_OBSERVATION_MEMBERSHIP_OR_REUSE')
            covered.add(trade.source_key)
    if covered != set(allowed):
        raise Blocked('REAL_UNASSESSED_SOURCE_PREFIX')


def require_real_scope_proof(system, proof, cutoff):
    """Use only immutable journal config pins, never request-supplied trust."""
    config = system.j.state['config']
    if not isinstance(proof, Mapping):
        raise Blocked('REAL_SCOPE_PROOF_REQUIRED')
    trust = trust_from_config(config)
    return verify_real_scope_proof(proof, trust=trust,
                                   timeframe=proof.get('timeframe', (proof.get('scope') or {}).get('timeframe')),
                                   cutoff=cutoff)

def verify_capture_window(*, context_completed_at, context_available_by,
                          raw_available_at, raw_available_by, cutoff, raw_event_time=None):
    """Different witnesses: pre-existing context versus later raw publication.

    A raw ACK is a retained post-commit upper bound, never the timestamp of the
    earlier context or an exact timestamp invented for the manifest link.
    """
    verify_publication_window(context_completed_at, context_available_by, cutoff)
    if not utc(raw_available_at) <= utc(raw_available_by) <= utc(cutoff):
        raise Blocked('REAL_RAW_AFTER_ADMISSION')
    if raw_event_time is not None and utc(context_completed_at) > utc(raw_event_time):
        raise Blocked('REAL_NATIVE_FUTURE_CONTEXT')


def _canary_digest(value):
    return sha256(json.dumps(value, sort_keys=True, separators=(',', ':'),
                             allow_nan=False).encode()).hexdigest()


def _canary_sealed(value):
    if not isinstance(value, dict) or value.get('content_sha256') != _canary_digest(
            {k: v for k, v in value.items() if k != 'content_sha256'}):
        raise Blocked('REAL_CANARY_CONTENT_HASH')
    return value


def _canary_child(root, relative):
    p = Path(relative)
    if p.is_absolute() or '..' in p.parts or not p.parts:
        raise Blocked('REAL_CANARY_PATH')
    result = root / p
    if result.resolve() != result.absolute() or not result.resolve().is_relative_to(root):
        raise Blocked('REAL_CANARY_PATH')
    return result


def _canary_clock(value, cutoff):
    from datetime import datetime, timezone
    if (not isinstance(value, dict) or type(value.get('wall_ns')) is not int
            or type(value.get('monotonic_ns')) is not int or value['monotonic_ns'] < 0):
        raise Blocked('REAL_CANARY_CLOCK_SCHEMA')
    moment = utc(value['wall_utc'])
    # Recorder wall_utc retains microseconds; wall_ns is the original OS sample.
    delta = moment - datetime(1970,1,1,tzinfo=timezone.utc)
    micros = (delta.days * 86400 + delta.seconds) * 1000000 + delta.microseconds
    if not 0 <= value['wall_ns'] - micros * 1000 < 1000:
        raise Blocked('REAL_CANARY_CLOCK_BINDING')
    if moment > utc(cutoff):
        raise Blocked('REAL_CANARY_AFTER_CUTOFF')
    return moment, value['monotonic_ns']


def read_retained_canary(trust: RealScopeTrust, *, capture_id: str, cutoff: str) -> dict:
    """Read the existing V2 recorder, without instantiating its writer/capture.

    Only retained bytes/local actions are verified. No coverage, aggression,
    economic ownership or REAL eligibility is minted. Locator/tip/code pins
    come from the independent inventory, never an incoming delivery packet.
    """
    if type(trust) is not RealScopeTrust:
        raise Blocked('REAL_TRUST_OBJECT_REQUIRED')
    return _read_retained_canary_inventory(trust.inventory(),capture_id=capture_id,cutoff=cutoff)

def _read_retained_canary_inventory(inv, *, capture_id, cutoff):
    ref = inv.get('canary_captures', {}).get(capture_id)
    if not isinstance(ref, dict):
        raise Blocked('REAL_CANARY_PIN_MISSING')
    try:
        root = Path(ref['root'])
        if not root.is_absolute() or root.resolve() != root:
            raise Blocked('REAL_CANARY_PATH')
        pins = _json(_read(Path(ref['pins_path']), ref['pins_sha256']))
        if pins.get('capture_identity') != str(root):
            raise Blocked('REAL_CANARY_CAPTURE_IDENTITY')
        retained = _json(_read(Path(ref['retained_files_path']),ref['retained_files_sha256']))
        if not isinstance(retained,dict):
            raise Blocked('REAL_CANARY_RETAINED_PINS')
        code = pins['sha256']
        if not isinstance(code, dict) or not code:
            raise Blocked('REAL_CANARY_PRODUCER_PINS')
        for name, checksum in code.items():
            _read(Path(name), checksum)
        mapping_path = root.parent.parent / 'src/recorder.py'
        if str(mapping_path) not in code:
            raise Blocked('REAL_CANARY_MAPPING_PIN')
        manifests = sorted((root / 'manifests').glob('*.json'))
        if (type(ref['manifest_count']) is not int or not 0 < len(manifests) <= 20000
                or len(manifests) != ref['manifest_count']):
            raise Blocked('REAL_CANARY_MANIFEST_COUNT')
        previous = None; sessions = {}; transport = {}; records = []
        deliveries = []; seen = {}; queue = []; files = {}; bytes_read = 0
        prior_native = None; discontinuities = []; scope_seen = False
        def raw_file(relative, expected_sha=None, expected_bytes=None):
            nonlocal bytes_read
            path = _canary_child(root, relative)
            checksum = expected_sha or files.get(relative, {}).get('sha256')
            if checksum is None:
                raise Blocked('REAL_CANARY_UNBOUND_FILE')
            raw = _read(path, checksum); bytes_read += len(raw)
            if bytes_read > 512 * 1024 * 1024:
                raise Blocked('REAL_CANARY_RESOURCE_CAP')
            if expected_bytes is not None and len(raw) != expected_bytes:
                raise Blocked('REAL_CANARY_FILE_SIZE')
            return raw
        for ordinal, path in enumerate(manifests, 1):
            # Manifest content hash is linked to the independently pinned tip.
            if str(path) not in retained:
                raise Blocked('REAL_CANARY_MANIFEST_PIN_REQUIRED')
            raw = _read(path,retained[str(path)])
            m = _canary_sealed(_json(raw))
            if (path.name != f'{ordinal:08d}.json' or m['seq'] != ordinal
                    or m['previous_manifest_sha'] != previous
                    or m.get('version') != 'DRA_PASSIVE_RAW_RECEIPT_RECORDER_V1'
                    or m.get('type') != 'CHUNK_MANIFEST_COMMITTED'):
                raise Blocked('REAL_CANARY_MANIFEST_CHAIN')
            if not isinstance(m.get('files'), list) or len(m['files']) > 9:
                raise Blocked('REAL_CANARY_FILES_SCHEMA')
            local_refs = {}
            for f in m['files']:
                if f['path'] in local_refs or (f['path'] in files and files[f['path']] != f):
                    raise Blocked('REAL_CANARY_FILE_REBINDING')
                local_refs[f['path']] = f; files[f['path']] = f
                raw_file(f['path'], f['sha256'], f['bytes'])
            if m['receipt_path'] not in local_refs:
                raise Blocked('REAL_CANARY_TRANSACTION_RECEIPT_BINDING')
            transaction = _canary_sealed(_json(raw_file(m['receipt_path'])))
            if (transaction.get('type') != 'RECORDER_TRANSACTION_RECEIPT'
                    or transaction.get('version') != m['version']
                    or transaction['files'] != [f for f in m['files'] if f['path'] != m['receipt_path']]):
                raise Blocked('REAL_CANARY_TRANSACTION_FILES')
            record = transaction['record']
            blob_refs = sorted((f['path'], f['sha256']) for f in transaction['files'])
            if m['request_sha'] != _canary_digest({'record': record, 'blobs': blob_refs}):
                raise Blocked('REAL_CANARY_REQUEST_BINDING')
            ack_path = _canary_child(root, 'receipts/ack-' + m['content_sha256'] + '.json')
            if str(ack_path) not in retained:
                raise Blocked('REAL_CANARY_ACK_PIN_REQUIRED')
            ack_raw = _read(ack_path,retained[str(ack_path)])
            ack = _canary_sealed(_json(ack_raw))
            if (ack.get('type') != 'POST_COMMIT_OBSERVED_ACK' or ack['seq'] != ordinal
                    or ack['manifest_sha'] != m['content_sha256']):
                raise Blocked('REAL_CANARY_ACK_BINDING')
            clocks = [_canary_clock(x, cutoff) for x in
                      (transaction['files_persisted_observed'], m['prepare_clock'], ack['observed_clock'])]
            if any(a[0] > b[0] or a[1] > b[1] for a, b in zip(clocks, clocks[1:])):
                raise Blocked('REAL_CANARY_PUBLICATION_CLOCK_ORDER')
            typ = record['type']
            if typ == 'CAPTURE_SCOPE':
                expected = {Path(p).name: h for p, h in code.items() if str(Path(p).parent) == str(mapping_path.parent)}
                if scope_seen or record['producer_sha256'] != expected or record['origin'] != 'LIVE_CAPTURE_RESEARCH_RECORDER':
                    raise Blocked('REAL_CANARY_SCOPE_PRODUCER')
                scope_seen = True
            elif typ == 'SESSION_STARTED':
                sid = record['session']
                if sid in sessions or record['origin'] != 'LIVE_CAPTURE_RESEARCH_RECORDER':
                    raise Blocked('REAL_CANARY_SESSION')
                sessions[sid] = record
            elif typ == 'TRANSPORT_SESSION_OBSERVATION':
                sid = record['session']
                if (sid not in sessions or record.get('endpoint') != 'wss://stream.binance.com:9443/ws/btcusdt@aggTrade'
                        or record.get('certificate_verified') is not True or record.get('hostname_verified') is not True
                        or record.get('api_keys_used') is not False or len(record.get('certificate_sha256', '')) != 64):
                    raise Blocked('REAL_CANARY_TRANSPORT_OBSERVATION')
                transport[sid] = {'manifest_sha256': m['content_sha256'], 'record': record}
            elif typ == 'DELIVERY':
                from .trend_event import Trade, canonical
                from .trend_evidence import RawOccurrence
                sid = record['session']
                if (sid not in sessions or sid not in transport or not scope_seen
                        or record['origin'] != 'LIVE_CAPTURE_RESEARCH_RECORDER'
                        or record['clock_domain'] != sessions[sid]['clock_domain']
                        or record['reconnect_generation'] != sessions[sid]['reconnect_generation']
                        or record['delivery_id'] != sid + ':' + str(record['delivery_sequence'])):
                    raise Blocked('REAL_CANARY_DELIVERY_SESSION')
                wire = raw_file(record['native_ref'])
                if len(wire) != record['message_bytes'] or sha256(wire).hexdigest() != record['native_message_sha256']:
                    raise Blocked('REAL_CANARY_NATIVE_IDENTITY')
                envelope = _json(wire); payload = envelope.get('data', envelope)
                if 'stream' in envelope and envelope['stream'] != 'btcusdt@aggTrade':
                    raise Blocked('REAL_NATIVE_SOURCE_DOMAIN')
                normalized = _json(raw_file(record['normalized_ref']))
                if (normalized != record['mapping'] or normalized.get('status') != 'ACCEPTED'
                        or normalized['mapping_version'] != 'SPOT_AGGTRADE_TO_DRA_CORE_V1'
                        or normalized['mapping_sha256'] != code[str(mapping_path)]
                        or normalized['parsed_object_sha256'] != _canary_digest(payload)
                        or normalized['core_sha256'] != _canary_digest(normalized['core'])):
                    raise Blocked('REAL_CANARY_MAPPING_BINDING')
                from decimal import Decimal
                if normalized['signed_base_quantity'] != str(-Decimal(payload['q']) if payload['m'] else Decimal(payload['q'])):
                    raise Blocked('REAL_CANARY_LOCAL_AGGRESSION_MAPPING')
                core = normalized['core']
                if (payload.get('e'), payload.get('s')) != ('aggTrade', 'BTCUSDT') or (core['market'], core['symbol'], core['stream']) != ('BINANCE_SPOT', 'BTCUSDT', 'AGG_TRADE'):
                    raise Blocked('REAL_NATIVE_SOURCE_DOMAIN')
                for field, native_field in [('native_id','a'), ('price','p'), ('quantity','q'), ('buyer_is_maker','m')]:
                    if type(core[field]) is not type(payload[native_field]) or core[field] != payload[native_field]:
                        raise Blocked('REAL_NATIVE_MESSAGE_MISMATCH')
                from datetime import datetime, timezone, timedelta
                for field, native_field in [('trade_time','T'), ('exchange_event_time','E')]:
                    if type(payload[native_field]) is not int or utc(core[field]) != datetime(1970,1,1,tzinfo=timezone.utc) + timedelta(milliseconds=payload[native_field]):
                        raise Blocked('REAL_NATIVE_MESSAGE_CLOCK_MISMATCH')
                for key in ('a','f','l','p','q','m','T','E'):
                    if normalized['fields'][key] != {'present': True, 'value': payload[key]}:
                        raise Blocked('REAL_CANARY_NATIVE_FIELD_BINDING')
                coverage = _canary_sealed(_json(raw_file(record['coverage_ref'])))
                if (coverage.get('type') != 'SOURCE_COVERAGE_OBSERVATION'
                        or coverage['delivery_id'] != record['delivery_id']
                        or coverage['native_message_sha256'] != record['native_message_sha256']
                        or coverage['native_fields'] != {k: normalized['fields'][k] for k in ('a','f','l')}
                        or coverage.get('complete_venue_coverage') is not False
                        or coverage.get('state') != 'COVERAGE_SEMANTICS_UNQUALIFIED'
                        or normalized.get('aggression_semantics') != 'PROJECT_MAPPING_ONLY / VENUE_UNQUALIFIED'):
                    raise Blocked('REAL_CANARY_UNAPPROVED_SEMANTICS')
                # Literal transport/queue receipts attest their own local actions.
                for suffix, clock in [('MESSAGE_RECEIVED',record['message_received']),('PARSE_OUTCOME',record['parse']['clock']),('NORMALIZATION_OUTCOME',normalized['normalization_ingest']),('QUEUE_APPEND_OUTCOME',record['queue']['clock'])]:
                    rel = 'receipts/' + Path(record['native_ref']).stem + '-' + suffix + '.json'
                    local = _canary_sealed(_json(raw_file(rel)))
                    if local.get('type') != suffix or local.get('delivery_id') != record['delivery_id'] or local.get('clock') != clock or local.get('native_message_sha256') != record['native_message_sha256']:
                        raise Blocked('REAL_CANARY_LOCAL_RECEIPT_BINDING')
                measured = [_canary_clock(x,cutoff) for x in (record['message_received'],record['parse']['clock'],normalized['normalization_start'],normalized['normalization_ingest'],record['queue']['clock'],transaction['files_persisted_observed'],m['prepare_clock'],ack['observed_clock'])]
                if any(a[0] > b[0] or a[1] > b[1] for a,b in zip(measured,measured[1:])):
                    raise Blocked('REAL_CANARY_DELIVERY_CLOCK_ORDER')
                if record['delivery_id'] in {d['delivery_id'] for d in deliveries}:
                    raise Blocked('REAL_CANARY_DUPLICATE_DELIVERY_ID')
                trade = Trade(**core,receive_time=record['message_received']['wall_utc'],payload_sha=normalized['core_sha256'])
                if error := trade.validate():
                    raise Blocked('REAL_CANARY_' + error)
                if trade.native_id in seen:
                    raise Blocked('REAL_CANARY_DUPLICATE_OR_CONFLICTING_NATIVE_ID')
                if prior_native is not None and trade.native_id != prior_native + 1:
                    discontinuities.append({'previous_observed':prior_native,'native_id':trade.native_id,'venue_gap_proven':False})
                if record['queue']['status'] != 'ADMITTED':
                    raise Blocked('REAL_CANARY_QUEUE_NOT_ADMITTED')
                queue.append(record['delivery_id'])
                if record['queue']['depth_after'] != len(queue):
                    raise Blocked('REAL_CANARY_QUEUE_DEPTH')
                # original_payload is the native DRA core serialization; literal
                # wire bytes retain their distinct original SHA/path below.
                packet = RawOccurrence(trade,canonical(core),'REAL_CANDIDATE',sid,
                    str(root / record['coverage_ref']),prior_native,ack['observed_clock']['wall_utc']).packet()
                RawOccurrence.from_dict(packet).validate(cutoff)
                deliveries.append({'delivery_id':record['delivery_id'],'packet':packet,
                    'native_ref':record['native_ref'],'native_sha256':record['native_message_sha256'],
                    'normalized_ref':record['normalized_ref'],'normalized_sha256':files[record['normalized_ref']]['sha256'],
                    'manifest_sha256':m['content_sha256'],'manifest_seq':ordinal,
                    'transaction_receipt_sha256':files[m['receipt_path']]['sha256'],
                    'ack_sha256':sha256(ack_raw).hexdigest(),'available_by':ack['observed_clock']['wall_utc'],
                    'transport_manifest_sha256':transport[sid]['manifest_sha256'],
                    'coverage':'COVERAGE_SEMANTICS_UNQUALIFIED','aggression':normalized['aggression_semantics']})
                seen[trade.native_id] = trade.payload_sha; prior_native = trade.native_id
            elif typ == 'QUEUE_DEQUEUED':
                if not queue or queue[0] != record['delivery_id']:
                    raise Blocked('REAL_CANARY_QUEUE_DEQUEUE')
                original = next(d for d in deliveries if d['delivery_id']==record['delivery_id'])
                if record['native_id'] != original['packet']['trade']['native_id'] or record['normalized_ref'] != original['normalized_ref']:
                    raise Blocked('REAL_CANARY_QUEUE_DEQUEUE_BINDING')
                queue.pop(0)
                if record['depth_after'] != len(queue):
                    raise Blocked('REAL_CANARY_QUEUE_DEPTH')
                _canary_clock(record['clock'],cutoff)
            records.append({'seq':ordinal,'type':typ,'manifest_sha256':m['content_sha256']})
            previous = m['content_sha256']
        if previous != ref['manifest_tip_sha256']:
            raise Blocked('REAL_CANARY_TIP_PIN')
        return {'capture_id':capture_id,'root':str(root),'pins_sha256':ref['pins_sha256'],
                'manifest_count':len(manifests),'manifest_tip_sha256':previous,
                'sessions':sessions,'transport':transport,'deliveries':deliveries,
                'observed_discontinuities':discontinuities,'pending_queue':queue,
                'records':records,'entry':'NO_ENTRY','coverage':'COVERAGE_SEMANTICS_UNQUALIFIED',
                'economic_authority':'NOT_ESTABLISHED','byte_verification':'VERIFIED_RETAINED_SOURCE_ONLY'}
    except Blocked:
        raise
    except (KeyError,TypeError,ValueError,AttributeError,OverflowError,OSError) as exc:
        raise Blocked('REAL_CANARY_INCOMPLETE_OR_CORRUPT') from exc


